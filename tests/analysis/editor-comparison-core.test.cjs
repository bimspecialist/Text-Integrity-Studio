'use strict';
const assert=require('node:assert/strict');
const {countWords,compareWords,proportionalScroll}=require('../../docs/analysis/editor-comparison-core.js');
assert.equal(countWords(''),0);
assert.equal(countWords('  \n \t '),0);
assert.equal(countWords('Revit 2027 5 mm [2]'),5);
assert.equal(countWords('قياس الجدار 5 mm وفق المخطط [2]'),7);
assert.throws(()=>countWords(undefined),TypeError);
const baseline='The wall measures 5 mm. Reference [2].';
const withChange=baseline+' The roof is unchanged.';
const result=compareWords(baseline,withChange);
assert(Object.isFrozen(result));
assert.equal(result.before,countWords(baseline));
assert.equal(result.after,countWords(withChange));
assert.equal(result.delta,4);
assert.equal(baseline,'The wall measures 5 mm. Reference [2].');
assert.equal(proportionalScroll(100,300,100,600,200),200);
assert.equal(proportionalScroll(9999,300,100,600,200),400);
assert.equal(proportionalScroll(80,100,100,800,300),0);
assert.equal(proportionalScroll(90,800,300,100,100),0);
assert.equal(proportionalScroll(0,600,200,800,200),0);
assert.throws(()=>proportionalScroll(NaN,300,100,600,200),RangeError);
assert.throws(()=>proportionalScroll(-1,300,100,600,200),RangeError);
console.log('PASS V8.7 word counts and proportional scrolling: English, Arabic, geometry, no source mutation');

'use strict';
const assert=require('node:assert/strict');
const f=require('../../docs/analysis/draft-find-replace-core.js');
const original='Revit a+b, a+b. 5 mm [2].';
assert.equal(f.matches(original,'a+b').items.length,2);
assert.equal(f.matches(original,'a.b').items.length,0,'not regex wildcard');
assert.equal(f.matches(original,'[2]').items.length,1,'brackets are literal');
assert.equal(f.matches(original,'').items.length,0);
assert.equal(f.matches('English english ENGLISH','english').items.length,3);
assert.equal(f.matches('English english ENGLISH','english',{caseSensitive:true}).items.length,1);
assert.equal(f.next(original,'a+b',8).item.start,11);
const preview=f.replaceOne(original,'a+b','q$&');
assert.equal(preview.text,'Revit q$&, a+b. 5 mm [2].');
assert.equal(original,'Revit a+b, a+b. 5 mm [2].');
assert.equal(f.replaceAll(original,'a+b','q$&').text,'Revit q$&, q$&. 5 mm [2].');
const ar='الجدار 5 mm ورسم الجدار [2].';
assert.equal(f.matches(ar,'الجدار').items.length,2);
assert.equal(f.replaceAll(ar,'الجدار','الحائط').text,'الحائط 5 mm ورسم الحائط [2].');
assert(Object.isFrozen(f.matches(ar,'الجدار').items));
assert.equal(f.replaceAll('x'.repeat(1200),'x','y').status,'TOO_MANY');
assert.equal(f.replaceAll('x'.repeat(30),'x','y'.repeat(9000)).status,'OUTPUT_TOO_LARGE');
assert.throws(()=>f.matches('some',null),TypeError);
assert.throws(()=>f.matches('some','x',{limit:2000}),RangeError);
console.log('PASS V8.8: safe literal Arabic/English find/replace, maximum replacements and inert $& notation');
